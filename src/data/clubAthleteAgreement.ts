export type AgreementClause = { title: string; content: string };

/**
 * מפצל תוכן סעיף לרשימת סעיפי־משנה.
 * תומך ב־\\n וגם בטקסט ישן שבו 1.1 / 2.1 וכו׳ היו באותה פיסקה.
 */
export function splitClauseItems(content: string): string[] {
  const normalized = content.replace(/\r\n/g, '\n').trim();
  if (!normalized) return [];

  // פיצול לפי מספרי סעיף־משנה בתחילת פריט (1.1 / 3.16 / 10.1)
  const byNumber = normalized
    .split(/(?=\d+\.\d+\s)/)
    .map(s => s.trim())
    .filter(Boolean);

  if (byNumber.length > 1) return byNumber;

  // פיצול לפי שורות
  const byLines = normalized
    .split('\n')
    .map(s => s.trim())
    .filter(Boolean);

  return byLines.length ? byLines : [normalized];
}

